/// Decodes base64 as kernels write it: IRkernel breaks it into lines of 72,
/// and padding may be left off.
pub fn decode_base64(text: &str) -> Result<Vec<u8>, base64::DecodeError> {
    use base64::Engine;
    use base64::engine::{DecodePaddingMode, GeneralPurpose, GeneralPurposeConfig};
    const LENIENT: GeneralPurpose = GeneralPurpose::new(
        &base64::alphabet::STANDARD,
        GeneralPurposeConfig::new().with_decode_padding_mode(DecodePaddingMode::Indifferent),
    );
    let text: Vec<u8> = text.bytes().filter(|b| !b.is_ascii_whitespace()).collect();
    LENIENT.decode(text)
}

/// Bytes as lowercase hexadecimal, the way checksums are written.
pub fn hex(bytes: &[u8]) -> String {
    use std::fmt::Write;
    let mut text = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        let _ = write!(text, "{byte:02x}");
    }
    text
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Request {
    pub id: u64,
    /// The window's project for document history. Older daemons ignore it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub project: Option<String>,
    #[serde(flatten)]
    pub call: Call,
}

