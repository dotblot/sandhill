//! Wire protocol between Sandhill clients (the Mac app, the `sandhill` CLI)
//! and the `sandhilld` daemon.
//!
//! Framing is one JSON object per line in both directions. A client sends
//! [`Request`]s; the daemon answers each with a [`ServerMessage::Response`]
//! carrying the same `id`, and pushes [`ServerMessage::Event`]s for sessions
//! the client subscribed to. The same stream works over a Unix socket or over
//! `ssh host sandhilld attach`.

pub mod client;

use serde::{Deserialize, Serialize};
use serde_json::Value;

/// Bumped whenever a change is not backwards compatible.
pub const PROTOCOL_VERSION: u32 = 1;

/// Prefix for event types generated by the daemon itself rather than a kernel.
pub const DAEMON_EVENT_PREFIX: &str = "sandhill.";
pub const EVENT_RUN_STARTED: &str = "sandhill.run_started";
pub const EVENT_RUN_FINISHED: &str = "sandhill.run_finished";
pub const EVENT_SESSION_ENDED: &str = "sandhill.session_ended";

/// Key used in place of a large or binary output value that was moved to the
/// blob store. The value becomes `{"sandhill_blob": "<sha256>", "size": n}`.
pub const BLOB_KEY: &str = "sandhill_blob";

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Request {
    pub id: u64,
    #[serde(flatten)]
    pub call: Call,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(tag = "method", content = "params", rename_all = "snake_case")]
pub enum Call {
    /// Returns [`PingReply`].
    Ping,
    /// Returns `Vec<KernelspecInfo>`.
    ListKernelspecs,
    /// Starts a kernel. Returns [`SessionInfo`].
    StartSession {
        kernel: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        cwd: Option<String>,
        /// The project the session belongs to (its folder), for listing
        /// sessions per project.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        project: Option<String>,
    },
    /// Returns `Vec<SessionInfo>`, including ended sessions.
    ListSessions,
    /// Queues code for execution. Returns [`RunStarted`].
    Execute {
        session: String,
        code: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        cell: Option<CellRef>,
    },
    Interrupt {
        session: String,
    },
    /// Stops the kernel for good.
    Shutdown {
        session: String,
    },
    /// Streams events for a session. With `since_seq`, journaled events after
    /// that sequence number are replayed first; without it, only new events
    /// are sent. Returns [`Subscribed`].
    Subscribe {
        session: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        since_seq: Option<i64>,
    },
    Unsubscribe {
        session: String,
    },
    /// Returns a page of journaled events as [`HistoryPage`].
    History {
        session: String,
        #[serde(default)]
        since_seq: i64,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        limit: Option<u32>,
    },
    /// Returns [`Blob`]. `near` names a document whose saved outputs may hold
    /// the blob (a `.qmd` sidecar), checked when the daemon's store lacks it.
    GetBlob {
        hash: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        near: Option<String>,
    },
    /// Reads a UTF-8 text file on the daemon's machine. Returns [`FileText`].
    ReadFile {
        path: String,
    },
    /// Replaces a text file atomically. With `expected_mtime_ms`, fails with
    /// an error starting with [`CONFLICT_ERROR`] if the file changed on disk
    /// since it was read. Returns [`FileWritten`].
    WriteFile {
        path: String,
        text: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        expected_mtime_ms: Option<i64>,
    },
    /// Returns `Vec<DirEntry>`, directories first, then by name.
    ListDir {
        path: String,
    },
    /// The latest run of every cell of a notebook file, from the journal,
    /// including runs still in progress. Returns [`FileOutputs`].
    FileOutputs {
        file: String,
    },
    /// Opens a folder as a project: records it as recently opened and
    /// returns [`ProjectInfo`] with the state saved for it.
    OpenProject {
        path: String,
    },
    /// Recently opened projects, most recent first. Returns `Vec<ProjectInfo>`
    /// without their saved state.
    ListRecentProjects,
    /// Saves a project's personal state (open tabs and the like). The daemon
    /// keeps it, not the project folder, so nothing is written into a
    /// shared repository.
    SaveProjectState {
        path: String,
        state: Value,
    },
    /// Removes a project from the recent list. Its files are untouched.
    ForgetProject {
        path: String,
    },
}

/// Prefix of the error returned when a write would overwrite changes made on
/// disk since the file was read.
pub const CONFLICT_ERROR: &str = "conflict:";

/// Which notebook cell a piece of code came from, so clients can put outputs
/// back under the right cell.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct CellRef {
    pub file: String,
    pub cell_id: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ServerMessage {
    Response {
        id: u64,
        #[serde(flatten)]
        outcome: Outcome,
    },
    Event {
        event: Event,
    },
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(rename_all = "snake_case")]
pub enum Outcome {
    Result(Value),
    Error(String),
}

/// One journaled message for a session. Kernel messages keep their Jupyter
/// `msg_type` and `content`; daemon events use the `sandhill.` prefix.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Event {
    /// Monotonic across the whole daemon; use it to resume after a disconnect.
    pub seq: i64,
    pub session: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub run: Option<String>,
    pub msg_type: String,
    /// Milliseconds since the Unix epoch, as recorded by the daemon.
    pub ts_ms: i64,
    pub content: Value,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct PingReply {
    pub protocol_version: u32,
    pub daemon_version: String,
    /// Home directory of the user the daemon runs as.
    #[serde(default)]
    pub home: String,
    #[serde(default)]
    pub hostname: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct KernelspecInfo {
    pub name: String,
    pub display_name: String,
    pub language: String,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum SessionStatus {
    Starting,
    Running,
    Ended,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct SessionInfo {
    pub id: String,
    pub kernel: String,
    pub language: String,
    pub cwd: String,
    pub pid: Option<u32>,
    pub status: SessionStatus,
    pub created_ms: i64,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ended_ms: Option<i64>,
    /// Highest event sequence number journaled for this session (0 if none).
    pub last_seq: i64,
    /// The project folder the session was started for, if any.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub project: Option<String>,
}

/// A folder opened as a project on the daemon's machine.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct ProjectInfo {
    /// Absolute path, without a trailing slash.
    pub path: String,
    /// The folder's name.
    pub name: String,
    pub opened_ms: i64,
    /// False when the folder no longer exists (moved or deleted).
    pub exists: bool,
    /// What the app saved with `save_project_state`; `null` if nothing yet,
    /// and always `null` in `list_recent_projects`.
    #[serde(default)]
    pub state: Value,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RunStarted {
    pub run: String,
    pub msg_id: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Subscribed {
    pub session: String,
    /// Events with a higher sequence number than this will be delivered.
    pub from_seq: i64,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct HistoryPage {
    pub events: Vec<Event>,
    /// Pass as `since_seq` to fetch the next page; equal to the request's
    /// `since_seq` when there is nothing more.
    pub next_seq: i64,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Blob {
    pub hash: String,
    /// The original JSON string value (base64 for binary MIME types).
    pub data: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct FileText {
    pub path: String,
    pub text: String,
    pub mtime_ms: i64,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct FileWritten {
    pub path: String,
    pub mtime_ms: i64,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum EntryKind {
    File,
    Dir,
    Other,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct DirEntry {
    pub name: String,
    pub kind: EntryKind,
    pub size: u64,
    pub mtime_ms: i64,
}

/// Outputs of the latest run of each cell of one file.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct FileOutputs {
    pub file: String,
    pub cells: Vec<CellOutputs>,
    /// The journal position these outputs reflect. Subscribe with this as
    /// `since_seq` to receive what happens next without gaps or repeats.
    pub seq: i64,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct CellOutputs {
    pub cell_id: String,
    pub run: String,
    pub session: String,
    pub language: String,
    pub code: String,
    pub started_ms: i64,
    /// `None` while the run is queued or executing.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub finished_ms: Option<i64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub status: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub execution_count: Option<u64>,
    /// nbformat 4 output objects. Large values are blob references.
    pub outputs: Vec<Value>,
}

/// Content of a [`EVENT_RUN_FINISHED`] event.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RunFinished {
    /// `ok`, `error` or `aborted`, as reported by the kernel.
    pub status: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub execution_count: Option<u64>,
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn unit_call_round_trips() {
        let req = Request {
            id: 7,
            call: Call::Ping,
        };
        let text = serde_json::to_string(&req).unwrap();
        assert_eq!(text, r#"{"id":7,"method":"ping"}"#);
        assert_eq!(serde_json::from_str::<Request>(&text).unwrap(), req);
    }

    #[test]
    fn call_with_params_parses_from_hand_written_json() {
        let req: Request = serde_json::from_value(json!({
            "id": 1,
            "method": "subscribe",
            "params": {"session": "abc", "since_seq": 10}
        }))
        .unwrap();
        assert_eq!(
            req.call,
            Call::Subscribe {
                session: "abc".into(),
                since_seq: Some(10)
            }
        );
    }

    #[test]
    fn server_messages_are_tagged() {
        let resp = ServerMessage::Response {
            id: 3,
            outcome: Outcome::Error("nope".into()),
        };
        assert_eq!(
            serde_json::to_value(&resp).unwrap(),
            json!({"type": "response", "id": 3, "error": "nope"})
        );
        let back: ServerMessage =
            serde_json::from_value(json!({"type": "response", "id": 3, "result": [1, 2]})).unwrap();
        assert_eq!(
            back,
            ServerMessage::Response {
                id: 3,
                outcome: Outcome::Result(json!([1, 2]))
            }
        );
    }
}
