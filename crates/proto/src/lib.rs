#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn unit_call_round_trips() {
        let req = Request {
            id: 7,
            call: Call::Ping,
        };
        let text = serde_json::to_string(&req).unwrap();
        assert_eq!(text, r#"{"id":7,"method":"ping"}"#);
        assert_eq!(serde_json::from_str::<Request>(&text).unwrap(), req);
    }

    #[test]
    fn call_with_params_parses_from_hand_written_json() {
        let req: Request = serde_json::from_value(json!({
            "id": 1,
            "method": "subscribe",
            "params": {"session": "abc", "since_seq": 10}
        }))
        .unwrap();
        assert_eq!(
            req.call,
            Call::Subscribe {
                session: "abc".into(),
                since_seq: Some(10)
            }
        );
    }

    #[test]
    fn server_messages_are_tagged() {
        let resp = ServerMessage::Response {
            id: 3,
            outcome: Outcome::Error("nope".into()),
        };
        assert_eq!(
            serde_json::to_value(&resp).unwrap(),
            json!({"type": "response", "id": 3, "error": "nope"})
        );
        let back: ServerMessage =
            serde_json::from_value(json!({"type": "response", "id": 3, "result": [1, 2]})).unwrap();
        assert_eq!(
            back,
            ServerMessage::Response {
                id: 3,
                outcome: Outcome::Result(json!([1, 2]))
            }
        );
    }
}
